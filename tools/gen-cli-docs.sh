#!/usr/bin/env bash
#
# Regenerate the CLI reference table of the documentation site (docs/user-guide/reference/cli.md) from
# the CLI's own `--help` output, so the docs cannot drift from the command definitions.
#
#   ./tools/gen-cli-docs.sh            # rewrite the page between the CLI REFERENCE markers
#   ./tools/gen-cli-docs.sh --check    # fail if the page is out of date (use in CI)
#   ./tools/gen-cli-docs.sh --stdout   # just print the table
#
# It runs THIS tree's CLI and nothing else: the native image built in this tree when it is newer than
# every CLI/core source, else a JVM run of the tree's own classes (`sbt cli/writeClasspath`). Never the
# `histmersion` on PATH — that is another build, and its help would be written into these docs (#910).

set -euo pipefail

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

MODE=write
case "${1:-}" in
  --check)  MODE=check ;;
  --stdout) MODE=stdout ;;
  "")       ;;
  *) echo "usage: $0 [--check|--stdout]" >&2; exit 1 ;;
esac

PAGE="docs/user-guide/reference/cli.md"
BEGIN="<!-- BEGIN CLI REFERENCE (generated by tools/gen-cli-docs.sh — do not edit by hand) -->"
END="<!-- END CLI REFERENCE -->"

# ── locate the CLI ───────────────────────────────────────────────────────────────────────────────
# sbt 2 puts module output under target/out/jvm/<scalaVersion>/<name>/, not modules/<m>/target/.
find_cli() { find target modules -type f -name histmersion-cli -perm -u+x -print 2>/dev/null | head -n 1; }
# a source of the CLI's commands newer than the binary: the binary's help is not this tree's
stale() { [ -n "$(find modules/cli/src/main modules/api modules/config modules/core -type f -name '*.scala' -newer "$1" -print 2>/dev/null | head -n 1)" ]; }

CLI_CMD=()
native="$(find_cli || true)"
if [ -n "$native" ] && ! stale "$native"; then
  CLI_CMD=("$native"); CLI_DESC="$native"
else
  [ -n "$native" ] && echo "the native CLI in this tree ($native) is older than its sources — using a JVM build instead" >&2
  echo "building this tree's CLI classes (sbt cli/writeClasspath)…" >&2
  if [ -n "${SBT:-}" ]; then
    read -r -a sbt_cmd <<< "$SBT"
    sbt_cmd+=("${NOFMT:-set every scalafmtOnCompile := false}")
  else
    sbt_cmd=(sbt --server -batch -J-Xss16m "set every scalafmtOnCompile := false")
  fi
  "${sbt_cmd[@]}" cli/writeClasspath >&2 || { echo "error: could not build this tree's CLI (sbt cli/writeClasspath failed)" >&2; exit 1; }
  cpfile="$(find target -type f -path '*histmersion-cli/classpath.txt' -print 2>/dev/null | head -n 1)"
  [ -n "$cpfile" ] || { echo "error: sbt cli/writeClasspath wrote no classpath.txt under target/ — cannot run this tree's CLI" >&2; exit 1; }
  java_bin="${JAVA_HOME:+$JAVA_HOME/bin/}java"
  command -v "$java_bin" >/dev/null 2>&1 || { echo "error: no java to run this tree's CLI with (set JAVA_HOME)" >&2; exit 1; }
  CLI_CMD=("$java_bin" -cp "$(cat "$cpfile")" com.histmersion.cli.histmersionCli); CLI_DESC="the JVM build ($cpfile)"
fi

# The help goes to stdout (an error's help to stderr), and
# the runtime may prepend Unsafe/native-access warnings there too. Merge the streams and drop those.
help_of() { "${CLI_CMD[@]}" "$@" --help 2>&1 | grep -v '^WARNING:' || true; }

# ── extract subcommand names + descriptions ──────────────────────────────────────────────────────
# The "Subcommands:" block is `    name` / `        description` line pairs. Used for the top level
# and again for each subcommand, since some (discover, assess, archive, calibre) nest one level.
subcommands_of() {
  help_of "$@" | awk '
    /^Subcommands:/ { inblock=1; next }
    inblock && /^    [a-z][a-z-]*$/ { name=$1; next }
    inblock && name != "" && /^        / {
      desc=$0; sub(/^ +/, "", desc);
      printf "%s\t%s\n", name, desc; name=""
    }
  '
}

# The flags/args line for one (sub)command. Subcommand help renders as
# `Usage: histmersion seed [--force] [<dir>]` on one line; a command that itself has subcommands puts the
# usages on following indented lines. Handle the inline form, fall back to the next non-empty line.
usage_of() { usages_of "$@" | head -n 1; }

# EVERY usage alternative of a (sub)command, one per line, with the leading `histmersion ` removed.
# A command that mixes subcommands with a direct form (e.g. `assess update-retractions` and
# `assess <citekey|doi>`) has one usage line for each, and both belong in the table.
usages_of() {
  help_of "$@" | awk '
    /^Usage:/ {
      line = $0; sub(/^Usage:[[:space:]]*/, "", line)
      if (line != "") { sub(/^histmersion[[:space:]]+/, "", line); print line; done=1 }
      inblock = 1; next
    }
    inblock && /^[[:space:]]+/ && NF { sub(/^[[:space:]]*histmersion[[:space:]]+/, "", $0); print; next }
    inblock && !NF { if (done || NR > 1) exit }
  ' | sed 's/[[:space:]]*$//'
}

table="$(subcommands_of)"

[ -n "$table" ] || { echo "could not parse subcommands from the help of $CLI_DESC" >&2; exit 1; }

# ── render ───────────────────────────────────────────────────────────────────────────────────────
# A description as a Markdown table cell: outside its `code spans`, a pipe would end the cell and a
# `<goal>` would be read as an HTML tag, so both are escaped there (the usages are code spans already).
cell() {
  printf '%s' "$1" | awk -F'`' -v OFS='`' \
    '{ for (i = 1; i <= NF; i += 2) { gsub(/\|/, "\\|", $i); gsub(/</, "\\&lt;", $i); gsub(/>/, "\\&gt;", $i) } print }'
}

render() {
  echo "$BEGIN"
  echo
  echo "| command | what it does |"
  echo "|---|---|"
  while IFS=$'\t' read -r name desc; do
    [ -n "$name" ] || continue
    # a command may itself have subcommands (discover/assess/archive/calibre): list each of THOSE,
    # with its own flags and its own description, rather than only the first one
    subs="$(subcommands_of "$name")"
    if [ -n "$subs" ]; then
      names="$(cut -f1 <<< "$subs")"
      while IFS=$'\t' read -r sub subdesc; do
        [ -n "$sub" ] || continue
        # …and a subcommand may nest once more (`places name add|rm|list`): list THOSE
        leaves="$(subcommands_of "$name" "$sub")"
        if [ -n "$leaves" ]; then
          while IFS=$'\t' read -r leaf leafdesc; do
            [ -n "$leaf" ] || continue
            args="$(usage_of "$name" "$sub" "$leaf")"
            printf '| `histmersion %s` | %s |\n' "${args:-$name $sub $leaf}" "$(cell "$leafdesc")"
          done <<< "$leaves"
          # …keeping its direct form, if it has one (`agent models [set | reset]` also runs alone)
          leafnames="$(cut -f1 <<< "$leaves")"
          usages_of "$name" "$sub" | while read -r line; do
            third="$(awk '{print $3}' <<< "$line")"
            grep -qxF "$third" <<< "$leafnames" && continue
            printf '| `histmersion %s` | %s |\n' "$line" "$(cell "$subdesc")"
          done
        else
          args="$(usage_of "$name" "$sub")"
          printf '| `histmersion %s` | %s |\n' "${args:-$name $sub}" "$(cell "$subdesc")"
        fi
      done <<< "$subs"
      # a command can ALSO have a direct form alongside its subcommands (`assess <citekey|doi>`):
      # any usage alternative whose first word is not one of the subcommands is that form
      usages_of "$name" | while read -r line; do
        first="$(awk '{print $2}' <<< "$line")"
        grep -qxF "$first" <<< "$names" && continue
        printf '| `histmersion %s` | %s |\n' "$line" "$(cell "$desc")"
      done
    else
      args="$(usage_of "$name")"
      printf '| `histmersion %s` | %s |\n' "${args:-$name}" "$(cell "$desc")"
    fi
  done <<< "$table"
  echo
  printf '%s\n' "Global: \`--server <url>\` overrides the configured server (\`\$HISTMERSION_SERVER_URL\`)."
  echo
  printf '%s\n' "Global, before the command: \`--by-plugin <name> --by-workflow <name>\` and \`--by-agent <definition> --by-provider <name> --by-model <name>\` name an automated caller (an agent: all five; a workflow's code: the first two), recorded as the creator of every record the command creates (else \`cli.agent.*\`, \`\$HISTMERSION_AGENT_*\`); without them a write is the person's, through the command line."
  echo
  echo "$END"
}

case "$MODE" in
  stdout) render; exit 0 ;;
esac

grep -qF "$BEGIN" "$PAGE" || { echo "marker not found in $PAGE: $BEGIN" >&2; exit 1; }
grep -qF "$END"   "$PAGE" || { echo "marker not found in $PAGE: $END" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.table"' EXIT
render > "$tmp.table"

awk -v begin="$BEGIN" -v end="$END" -v tablefile="$tmp.table" '
  index($0, begin) == 1 { while ((getline line < tablefile) > 0) print line; skip=1; next }
  index($0, end)   == 1 { skip=0; next }
  !skip { print }
' "$PAGE" > "$tmp"

if [ "$MODE" = check ]; then
  if diff -q "$PAGE" "$tmp" >/dev/null; then
    echo "$PAGE: the CLI reference is up to date."
  else
    echo "$PAGE: the CLI reference is STALE — run ./tools/gen-cli-docs.sh (just cli-docs)" >&2
    diff -u "$PAGE" "$tmp" || true
    exit 1
  fi
else
  mv "$tmp" "$PAGE"
  trap - EXIT
  rm -f "$tmp.table"
  echo "$PAGE: CLI reference regenerated from $CLI_DESC"
fi
