#!/usr/bin/env bash
#
# Regenerate the CLI reference table in README.md from the CLI's own `--help` output, so the docs
# cannot drift from decline's command definitions.
#
#   ./tools/gen-cli-docs.sh            # rewrite README.md between the CLI REFERENCE markers
#   ./tools/gen-cli-docs.sh --check    # fail if README.md is out of date (use in CI)
#   ./tools/gen-cli-docs.sh --stdout   # just print the table
#
# It uses, in order: an already-built native image, `histdb` on PATH, or `sbt cli/nativeImage`.

set -euo pipefail

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

MODE=write
case "${1:-}" in
  --check)  MODE=check ;;
  --stdout) MODE=stdout ;;
  "")       ;;
  *) echo "usage: $0 [--check|--stdout]" >&2; exit 1 ;;
esac

README="README.md"
BEGIN="<!-- BEGIN CLI REFERENCE (generated by tools/gen-cli-docs.sh — do not edit by hand) -->"
END="<!-- END CLI REFERENCE -->"

# ── locate the CLI ───────────────────────────────────────────────────────────────────────────────
# sbt 2 puts module output under target/out/jvm/<scalaVersion>/<name>/, not modules/<m>/target/.
find_cli() { find target modules -type f -name histdb-cli -perm -u+x -print 2>/dev/null | head -n 1; }

CLI="$(find_cli || true)"
if [ -z "$CLI" ] && command -v histdb >/dev/null 2>&1; then CLI="$(command -v histdb)"; fi
if [ -z "$CLI" ]; then
  echo "no CLI binary found — building it (sbt cli/nativeImage)…" >&2
  sbt --server -batch cli/nativeImage >&2
  CLI="$(find_cli || true)"
fi
[ -n "$CLI" ] || { echo "could not build or find the histdb CLI" >&2; exit 1; }

# decline's help goes to STDERR (cli/Main.scala prints it with System.err.println) and exits 1, and
# the runtime may prepend Unsafe/native-access warnings there too. Merge the streams and drop those.
help_of() { "$CLI" "$@" --help 2>&1 | grep -v '^WARNING:' || true; }

# ── extract subcommand names + descriptions ──────────────────────────────────────────────────────
# The "Subcommands:" block is `    name` / `        description` line pairs. Used for the top level
# and again for each subcommand, since some (discover, assess, archive, calibre) nest one level.
subcommands_of() {
  help_of "$@" | awk '
    /^Subcommands:/ { inblock=1; next }
    inblock && /^    [a-z][a-z-]*$/ { name=$1; next }
    inblock && name != "" && /^        / {
      desc=$0; sub(/^ +/, "", desc);
      printf "%s\t%s\n", name, desc; name=""
    }
  '
}

# The flags/args line for one (sub)command. Subcommand help renders as
# `Usage: histdb seed [--force] [<dir>]` on one line; a command that itself has subcommands puts the
# usages on following indented lines. Handle the inline form, fall back to the next non-empty line.
usage_of() { usages_of "$@" | head -n 1; }

# EVERY usage alternative of a (sub)command, one per line, with the leading `histdb ` removed.
# A command that mixes subcommands with a direct form (e.g. `assess update-retractions` and
# `assess <citekey|doi>`) has one usage line for each, and both belong in the table.
usages_of() {
  help_of "$@" | awk '
    /^Usage:/ {
      line = $0; sub(/^Usage:[[:space:]]*/, "", line)
      if (line != "") { sub(/^histdb[[:space:]]+/, "", line); print line; done=1 }
      inblock = 1; next
    }
    inblock && /^[[:space:]]+/ && NF { sub(/^[[:space:]]*histdb[[:space:]]+/, "", $0); print; next }
    inblock && !NF { if (done || NR > 1) exit }
  ' | sed 's/[[:space:]]*$//'
}

table="$(subcommands_of)"

[ -n "$table" ] || { echo "could not parse subcommands from '$CLI --help'" >&2; exit 1; }

# ── render ───────────────────────────────────────────────────────────────────────────────────────
render() {
  echo "$BEGIN"
  echo
  echo "| command | what it does |"
  echo "|---|---|"
  while IFS=$'\t' read -r name desc; do
    [ -n "$name" ] || continue
    # a command may itself have subcommands (discover/assess/archive/calibre): list each of THOSE,
    # with its own flags and its own description, rather than only the first one
    subs="$(subcommands_of "$name")"
    if [ -n "$subs" ]; then
      names="$(cut -f1 <<< "$subs")"
      while IFS=$'\t' read -r sub subdesc; do
        [ -n "$sub" ] || continue
        args="$(usage_of "$name" "$sub")"
        printf '| `histdb %s` | %s |\n' "${args:-$name $sub}" "$subdesc"
      done <<< "$subs"
      # a command can ALSO have a direct form alongside its subcommands (`assess <citekey|doi>`):
      # any usage alternative whose first word is not one of the subcommands is that form
      usages_of "$name" | while read -r line; do
        first="$(awk '{print $2}' <<< "$line")"
        grep -qxF "$first" <<< "$names" && continue
        printf '| `histdb %s` | %s |\n' "$line" "$desc"
      done
    else
      args="$(usage_of "$name")"
      printf '| `histdb %s` | %s |\n' "${args:-$name}" "$desc"
    fi
  done <<< "$table"
  echo
  printf '%s\n' "Global: \`--server <url>\` overrides the configured server (\`\$HISTDB_SERVER_URL\`)."
  echo
  echo "$END"
}

case "$MODE" in
  stdout) render; exit 0 ;;
esac

grep -qF "$BEGIN" "$README" || { echo "marker not found in $README: $BEGIN" >&2; exit 1; }
grep -qF "$END"   "$README" || { echo "marker not found in $README: $END" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.table"' EXIT
render > "$tmp.table"

awk -v begin="$BEGIN" -v end="$END" -v tablefile="$tmp.table" '
  index($0, begin) == 1 { while ((getline line < tablefile) > 0) print line; skip=1; next }
  index($0, end)   == 1 { skip=0; next }
  !skip { print }
' "$README" > "$tmp"

if [ "$MODE" = check ]; then
  if diff -q "$README" "$tmp" >/dev/null; then
    echo "README.md CLI reference is up to date."
  else
    echo "README.md CLI reference is STALE — run ./tools/gen-cli-docs.sh" >&2
    diff -u "$README" "$tmp" || true
    exit 1
  fi
else
  mv "$tmp" "$README"
  trap - EXIT
  rm -f "$tmp.table"
  echo "README.md CLI reference regenerated from $CLI"
fi
