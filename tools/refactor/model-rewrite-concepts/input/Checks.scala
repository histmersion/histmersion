package conceptfixture

import io.github.iltotore.iron.*
import scala.compiletime.testing.typeChecks

@main def checkConcepts(): Unit =
  assert(!typeChecks("conceptfixture.Report(label = \"raw\")"))
  assert(!typeChecks("conceptfixture.Report(label = conceptfixture.Title(\"wrong concept\"))"))
  assert(!typeChecks("conceptfixture.Report(authors = List(\"raw\"))"))
  assert(!typeChecks("conceptfixture.Report(doi = Some(\"raw\"))"))
  val r = Calls.positional
  assert(Calls.fetched == "!fetched")
  assert(Calls.fetchedForwarded(r) == "!k")
  assert(Calls.fetchedRaw == "raw")
  assert(Calls.fetchedLambda == "!constant")
  assert(!typeChecks("conceptfixture.Calls.fetch(using \"!\")((s: String) => s, conceptfixture.Label(\"x\"))"))
  assert(Calls.leadingImplicit(using "!") == "!implicit")
  assert(Calls.leadingExplicit == "!explicit")
  assert(Calls.leadingNamed == "?named")
  assert(Calls.leadingForwarded(r) == "!k")
  assert(!typeChecks("conceptfixture.Calls.leading(using \"!\")(\"raw\")"))
  assert(Calls.contextImplicit(using "!") == "implicit!")
  assert(Calls.contextExplicit == "explicit!")
  assert(Calls.contextNamed == "named?")
  assert(Calls.contextForwarded(r) == "k!")
  assert(Calls.unrelatedCurried("raw")("!") == "raw!")
  assert(!typeChecks("conceptfixture.Calls.contextual(\"raw\")(using \"!\")"))
  assert(r.label.value == "k" && r.title.value == "t")
  assert(r.bytes.value == 5L && r.lat.value == 1.5 && r.year.value == 1999)
  assert(r.doi.map(_.value).contains("d"))
  assert(r.authors.map(_.value) == List("a", "b"))
  assert(Calls.forwarded(r) == r)
  assert(Calls.copied(r).title.value == "changed")
  assert(Calls.label(r) == r.label && Calls.authors(r) == r.authors)
  assert(Calls.echoed.value == "echo")
  val named = Calls.named
  assert(Calls.evaluations == 1 && named.authors.map(_.value) == List("a", "b"))
  assert(Calls.defaults.doi.isEmpty && Calls.defaults.authors.isEmpty)
  assert(Calls.defaults.bytes.value == 0L)
  assert(Calls.unrelated == Unrelated("raw", 3L))
  assert(Rendering.render(r) == "a|bd" && Rendering.evaluations == 1)
  assert(Rendering.render(Calls.defaults) == "missing")
  assert(Rendering.normalized(r).contains("d"))
  assert(Rendering.forwarded(r) == r)
  assert(Rendering.sorted(List(r, Calls.defaults)) == List(Calls.defaults, r))
  assert(Rendering.total(List(r, Calls.defaults, r)) == 10L)
  assert(Rendering.below(List(r, Calls.defaults), r) == List(Calls.defaults))
  assert(Calls.repeatedAliases.map(_.value) == Set("a", "b"))
  assert(Calls.forwardedAliases(Calls.repeatedAliases) == Calls.repeatedAliases)
  assert(Calls.aliasContains(Calls.repeatedAliases, Label("a")))
  assert(!Calls.aliasContains(Calls.repeatedAliases, Label("c")))
  assert(Calls.aliases().isEmpty)
  assert(Rendering.titles(List(r, Calls.defaults)) == List(Calls.defaults, r))
  assert(Rendering.quantityTotal(Quantities(List(ByteCount(4L), ByteCount(7L)), Some(ByteCount(9L)))) == 20L)
  assert(Rendering.quantityTotal(Quantities(Nil, None)) == 0L)
  assert(Rendering.typedTotal(List(r, r)).value == 10L)
  assert(Rendering.totalText(List(r, r)) == "10")
  assert(Rendering.totalRecord(List(r, r)).bytes.value == 10L)
  assert(Calls.nested.authors.map(_.map(_.value)).contains(List("a", "b")))
  assert(Calls.forwardNested(Calls.nested) == Calls.nested)
  assert(Calls.emptyNested.authors.contains(Nil))
  assert(Nested().authors.isEmpty)
  assert(Calls.normalizedDoi(Report(doi = Some(Doi(" d "))), r).map(_.value).contains("d"))
  assert(Calls.normalizedDoi(Report(doi = Some(Doi(" "))), r).isEmpty)
  assert(Calls.normalizedDoi(Calls.defaults, r) == r.doi)
  assert(!typeChecks("conceptfixture.Nested(Some(List(\"raw\")))"))
  assert(!typeChecks("conceptfixture.Calls.aliases(Set(\"raw\"))"))
