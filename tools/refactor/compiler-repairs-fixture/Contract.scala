package compilerfixture

object Contract:
  @main def verifyCompilerRepairs(): Unit =
    OrderedChecks.check()
    ComparisonConstruction.check()
    assert(Owned.raw(Owned.Text("one")) == "one")
    assert(Owned.alias(Owned.Text("alias")) == "alias")
    assert(Owned.upper(Owned.Text("one")) == "ONE")
    assert(Owned.increment(Owned.Count(Int.MaxValue)) == Int.MinValue)
    assert(Owned.sum(Owned.Count(3), Owned.Count(4)) == 7)
    var generatedLeftCalls = 0
    assert(Owned.generatedLeft(() => { generatedLeftCalls += 1; 3 }, Owned.Count(4)) == 7)
    assert(generatedLeftCalls == 1)
    assert(Owned.negative(Owned.Count(7)) == -7)
    assert(Owned.small(Owned.Count(3)) && !Owned.small(Owned.Count(4)))
    assert(Owned.wide(Owned.Count(Int.MinValue)) == Int.MinValue.toLong)
    assert(Owned.flag(Owned.Flag(true)) && !Owned.not(Owned.Flag(true)))
    assert(Owned.length(Owned.Bytes(Array[Byte](1, 2))) == 2)
    assert(Owned.path(Owned.Text("one")).toString == "one")
    assert(OwnedRecord(OwnedRecord.Text(" one ")).trimmed == "one")
    assert(ConstructOnly.text("one").value == "one")
    assert(ConstructMode.Finishing.wire.value == "finish")
    assert(ConstructOnly.large.value == 7L)
    assert(ConstructOnly.texts(List("one", "two")).map(_.value) == List("one", "two"))
    val constructed = ConstructOnly.record("one", 7)
    assert(constructed.text.value == "one" && constructed.count.value == 7 && !constructed.flag)
    Comparisons.check()
    Comparisons.texts(Set(Values.Text("one"), Values.Text("two")))
    assert(scala.util.Try(Comparisons.texts(Set(Values.Text("one")))).isFailure)
    Comparisons.empties(Values.Text("one"))
    Comparisons.multiline()
    Comparisons.emptyMap(Values.Text("one"))
    assert(scala.util.Try(Comparisons.nonemptyMap(Values.Text("one"))).isFailure)
    Overloads.multilineFlag()
    assert(Comparisons.equalField(new Record(Values.Text("one"), Values.Count(7))))
    assert(!Comparisons.equalField(new Record(Values.Text("two"), Values.Count(7))))
    assert(!Comparisons.unequalField(new Record(Values.Text("one"), Values.Count(7))))
    assert(Comparisons.unequalField(new Record(Values.Text("two"), Values.Count(7))))
    Record.legacyCalls = 0
    Record.defaultCalls = 0
    assert(Overloads.named("named", 7).text.value == "named")
    assert(Overloads.positional("positional", 8).count.value == 8)
    assert(Record.legacyCalls == 2 && Record.defaultCalls == 0)
    assert(Overloads.primary("primary", 9).flag)
    assert(Record.legacyCalls == 2 && Record.defaultCalls == 0)
    assert(new Record(Values.Text("direct"), Values.Count(1)).flag)
    assert(Record.defaultCalls == 1)
    assert(Overloads.empty.values.isEmpty && Overloads.empty.optional.isEmpty)
    assert(Overloads.populated.optional.map(_.value).contains("raw"))
    assert(Overloads.texts(Set("one", "two")).map(_.value) == Set("one", "two"))
    val rawBytes = Array[Byte](1, 2)
    assert(Overloads.bytes(rawBytes).value eq rawBytes)
    assert(Positive.singleton.value == 2)
    Comparisons.leftError(Left(Values.Other("bad")))
    assert(scala.util.Try(Comparisons.leftError(Left(Values.Other("other")))).isFailure)
    assert(scala.util.Try(Comparisons.leftError(Right(7))).isFailure)
    Comparisons.refinedTuple(Values.Text("one"))
    assert(Positive.nullText.value == null)
    assert(Clash.Ref.Vault("shown").shown == "shown")
    assert(Positive.widened(Int.MaxValue).value == Int.MaxValue.toLong)
    assert(Positive.widened(Int.MinValue).value == Int.MinValue.toLong)
    assert(Positive.fallback(Values.Text(" one ")) == "one")
    assert(Positive.fallback(Values.Text(null)) == "")
    assert(Positive.unionMember(Values.Text(" one ")) == "one")
    assert(Positive.unionMember(Values.Text(null)) == "")
    assert(scala.util.Try(Comparisons.mismatch()).isFailure)
    val text = Positive.produce("hello")
    assert(Positive.consume(text) == "hello")
    assert(Positive.upper(text) == "HELLO")
    assert(Positive.number.value == 7)
    val bytes = new java.io.ByteArrayOutputStream
    Positive.output(new java.io.PrintStream(bytes), text)
    assert(bytes.toString("UTF-8") == "hello")
    assert(Positive.produce(null).value == null)
    assert(Positive.combined("hi").value == "HI!")
    assert(Positive.optional("hello").map(_.value).contains("hello"))
    assert(Positive.optional(null).isEmpty)
    assert(Positive.pattern(List(Positive.produce("resolve"))))
    assert(!Positive.pattern(List(Positive.produce("other"))))
    assert(Positive.texts(List("one", "two")).map(_.value) == List("one", "two"))
    assert(Positive.maybe(None).isEmpty)
    assert(Positive.maybe(Some("one")).map(_.value).contains("one"))
    assert(Positive.errors(Left("bad")).left.map(_.value) == Left("bad"))
    assert(Positive.errors(Right(7)) == Right(7))
    assert(Positive.mixed(("one", 7))._1.value == "one")
    var created = 0
    val adapted = Positive.adapted(() => { created += 1; (text: Values.Text) => text.value.length })
    assert(created == 1)
    assert(adapted("one") == 3)
    assert(adapted("seven") == 5)
    assert(created == 1)
    assert(Positive.path(Positive.produce("one")).toString == "one")
    assert(Positive.same(Positive.produce("one")))
    assert(!Positive.same(Positive.produce("other")))
    assert(Positive.attempted("one").map(_.value).contains("one"))
    assert(Positive.attempted(null).isDefined)
    assert(Positive.attempted(null).get.value == null)
    assert(Positive.paths(List(Positive.produce("one"))).map(_.toString) == List("one"))
    assert(Positive.failure.left.map(_.value) == Left("IllegalStateException"))
