/** Flyway schema versioning. Migrations are SQL resources under `db/migration/V###__name.sql`, enumerated by the
  * build-generated `db/migration/index.txt` (Flyway's classpath scanning does not work inside a native image; this
  * provider works everywhere). The chain was squashed into `V109__schema.sql` on 2026-11-02; a database the chain
  * before it built is given a baseline at 109 instead ([[squashHistory]]).
  */
object Migrate:
  type MigrationName = MigrationName.T
  object MigrationName extends Newtype[String, Pure]
  type RetryAttempts = RetryAttempts.T
  object RetryAttempts extends Newtype[Int, Pure]
  type RoleName = RoleName.T
  object RoleName extends Newtype[String, Pure]
  type Version = Version.T
  object Version extends Newtype[String, Pure]

  private val Base = "db/migration"

  /** Migration file names, from the generated index. Public for the test that keeps it honest. */
  def migrationNames: List[MigrationName] =
    val is = Option(getClass.getClassLoader.getResourceAsStream(s"$Base/index.txt"))
      .getOrElse(throw new IllegalStateException(s"missing $Base/index.txt (generated by sbt)"))
    try
      scala.io.Source
        .fromInputStream(is, "UTF-8")
        .getLines()
        .map(_.trim)
        .filter(_.nonEmpty)
        .map(MigrationName(_))
        .toList
    finally is.close()

  final private class Res(name: MigrationName) extends LoadableResource:
    def read(): Reader =
      InputStreamReader(getClass.getClassLoader.getResourceAsStream(s"$Base/${name.value}"), Charset.forName("UTF-8"))
    def getAbsolutePath: String = s"$Base/${name.value}"
    def getAbsolutePathOnDisk: String = getAbsolutePath
    def getFilename: String = name.value
    def getRelativePath: String = name.value

  private val provider: ResourceProvider = new ResourceProvider:
    private def all = migrationNames.map(Res(_))
    def getResource(name: String): LoadableResource =
      all.find(r => r.getAbsolutePath == name || r.getFilename == name).orNull
    def getResources(prefix: String, suffixes: Array[String]): java.util.Collection[LoadableResource] =
      all
        .filter(r => r.getFilename.startsWith(prefix) && suffixes.exists(r.getFilename.endsWith))
        .map(r => r: LoadableResource)
        .asJavaCollection

  private[histmersion] def flyway(ds: DataSource): Flyway =
    Flyway
      .configure()
      .dataSource(ds)
      .locations(s"classpath:$Base")
      .resourceProvider(provider)
      .baselineOnMigrate(false)
      .loggers("slf4j")
      .load()

  /** Apply pending migrations; returns the current schema version.
    *
    * Safe when several servers migrate databases of ONE cluster at the same moment (#828). Roles are cluster-global
    * while migrations are per-database, and V011's `IF NOT EXISTS … CREATE ROLE` is a check-then-act: two fresh
    * databases both pass the check and the second CREATE fails on the role-name index (V011 is applied and cannot
    * change). So the role is created first by [[ensureRole]], which tolerates losing that race; and a migration that
    * fails on a catalog-level collision ([[transient]] — e.g. two `ALTER ROLE … SET` on the same role) is retried:
    * Postgres rolls the failed migration back, so a retry starts from where the last success left off.
    */
  def run(ds: DataSource): Version =
    ensureRole(ds, QueryRole)
    val _ = squashHistory(ds)
    retrying(MigrateAttempts)(flyway(ds).migrate())
    current(ds).getOrElse(Version("?"))

  /** The version the chain was squashed at (2026-11-02): its one migration, `V109__schema.sql`, is the schema the 109
    * migrations before it built, so the version every database, backup and bundle carries keeps its meaning.
    */
  val SquashedAt: Version = Version("109")

  /** A database the chain before the squash built (its history starts at `001`): its history is replaced by one
    * baseline at [[SquashedAt]], in one transaction, and nothing else is touched — the schema already is the one the
    * squashed migration builds. A database that chain had not brought to [[SquashedAt]], or that has a failed
    * migration, is refused: a build from before the squash brings it there first. Does nothing to a database without a
    * history or with the squashed one. Returns whether it replaced the history.
    */
  private[histmersion] def squashHistory(ds: DataSource): Boolean =
    val c = ds.getConnection
    try
      if !historyExists(c) then false
      else
        c.setAutoCommit(false)
        try
          val st = c.createStatement()
          try
            val _ = st.execute("LOCK TABLE flyway_schema_history IN EXCLUSIVE MODE")
            val rs = st.executeQuery(
              """SELECT count(*) FILTER (WHERE version IN ('1', '001')),
                |       count(*) FILTER (WHERE NOT success),
                |       (SELECT version FROM flyway_schema_history WHERE version IS NOT NULL
                |         ORDER BY string_to_array(version, '.')::int[] DESC LIMIT 1)
                |FROM flyway_schema_history""".stripMargin
            )
            val _ = rs.next()
            val (old, failed, top) = (rs.getInt(1), rs.getInt(2), Option(rs.getString(3)))
            if old == 0 then { c.rollback(); false }
            else if failed > 0 || !top.exists(_.toIntOption.contains(SquashedAt.value.toInt)) then
              throw IllegalStateException(
                s"this database is at schema ${top.getOrElse("?")} of the migration chain before the 2026-11-02 " +
                  s"squash${if failed > 0 then s", with $failed failed migration(s)" else ""}; start it once with a " +
                  s"build from before the squash, which brings it to $SquashedAt, then with this one"
              )
            else
              val _ = st.executeUpdate("DELETE FROM flyway_schema_history")
              val _ = st.executeUpdate(
                s"""INSERT INTO flyway_schema_history
                   |  (installed_rank, version, description, type, script, checksum, installed_by, execution_time, success)
                   |VALUES (1, '${SquashedAt.value}', '<< Flyway Baseline >>', 'BASELINE', '<< Flyway Baseline >>', NULL,
                   |        current_user, 0, true)""".stripMargin
              )
              c.commit()
              scribe.info(s"migration history before the squash replaced by a baseline at $SquashedAt")
              true
          finally st.close()
        catch
          case e: Throwable =>
            c.rollback()
            throw e
    finally c.close()

  /** The read-only login role migration V011 creates (and `QueryAccess.provision` configures). */
  val QueryRole: RoleName = RoleName("histmersion_query")

  private val MigrateAttempts: RetryAttempts = RetryAttempts(5)

  private val RoleNamePattern = "^[a-z_][a-z0-9_]*$".r

  /** Create login role `name` with V011's attributes unless it exists — race-free: a concurrent creator in another
    * database of the cluster is not an error, and neither is an application role that may not create roles (V011 then
    * says so, as it always did). Idempotent.
    */
  def ensureRole(ds: DataSource, name: RoleName): Unit =
    require(RoleNamePattern.matches(name.value), s"not a plain role name: ${name.value}")
    val c = ds.getConnection
    try
      val st = c.createStatement()
      try
        val _ = st.execute(s"""DO $$$$
             |BEGIN
             |  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${name.value}') THEN
             |    CREATE ROLE ${name.value} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION;
             |  END IF;
             |EXCEPTION WHEN duplicate_object OR unique_violation OR insufficient_privilege THEN
             |  NULL;
             |END
             |$$$$""".stripMargin)
      finally st.close()
    finally c.close()

  /** SQLSTATEs of a collision with a concurrent writer of the same CLUSTER catalog row: a role created twice
    * (`unique_violation`, `duplicate_object`), a serialization failure or a deadlock.
    */
  private val TransientStates = Set("23505", "42710", "40001", "40P01")

  /** Whether `e` (or a cause) is a collision with another session that a retry resolves — including Postgres's "tuple
    * concurrently updated" (XX000), what two `ALTER ROLE … SET` on one role meet.
    */
  def transient(e: Throwable): Boolean =
    Iterator.iterate(e)(_.getCause).takeWhile(_ != null).take(16).exists {
      case s: java.sql.SQLException =>
        TransientStates.contains(s.getSQLState) ||
        (s.getSQLState == "XX000" && Option(s.getMessage).exists(_.contains("concurrently updated")))
      case _ => false
    }

  /** Run `f`, again (up to `attempts` times, with a short growing pause) while it fails [[transient]]ly. */
  private[histmersion] def retrying[A](attempts: RetryAttempts)(f: => A): A =
    @annotation.tailrec
    def go(n: Int): A =
      scala.util.Try(f) match
        case scala.util.Success(a)                                       => a
        case scala.util.Failure(e) if n < attempts.value && transient(e) =>
          scribe.warn(
            s"migration collided with a concurrent one (${e.getMessage.take(200)}); retry $n of ${attempts.value - 1}"
          )
          Thread.sleep(100L * n + scala.util.Random.nextInt(100))
          go(n + 1)
        case scala.util.Failure(e) => throw e
    go(1)

  /** Flyway `validate` — run after a restore (plan §1.10) to prove the dump we just loaded carries the schema this
    * build expects. Right = the current version, Left = why validation failed.
    */
  def validate(ds: DataSource): Either[Problem, Version] =
    scala.util
      .Try(squashHistory(ds))
      .toEither
      .left
      .map(e => Problem.Io.Database(Problem.Io.DbOp.Migrate, External.Reported.of(e)))
      .flatMap { _ =>
        val r = flyway(ds).validateWithResult()
        if r.validationSuccessful then Right(current(ds).getOrElse(Version("?")))
        else
          Left(
            Problem.Io.Database(
              Problem.Io.DbOp.Migrate,
              External.Reported.of(
                Option(r.getAllErrorMessages).map(_.trim).filter(_.nonEmpty).getOrElse("schema validation failed")
              )
            )
          )
      }

  /** The schema version: the highest successfully applied versioned migration, as Flyway's `info().current()` reports
    * it (`"050"`), or `None` before the first migration.
    *
    * Read from `flyway_schema_history` directly, NOT through a Flyway instance (#880): `/api/health` asks for it on
    * every call, and each Flyway build logged its long `Database: jdbc:…` line and the "PostgreSQL N is newer than this
    * version of Flyway" warning — several times per start and once per health check. Flyway itself is now built only to
    * migrate or validate.
    */
  def current(ds: DataSource): Option[Version] =
    val c = ds.getConnection
    try
      if !historyExists(c) then None
      else
        // versions are dotted numbers (`050`, `1`): compared as int arrays, not as text
        val st = c.prepareStatement("""SELECT version FROM flyway_schema_history WHERE success AND version IS NOT NULL
            |ORDER BY string_to_array(version, '.')::int[] DESC LIMIT 1""".stripMargin)
        try
          val rs = st.executeQuery()
          Option.when(rs.next())(Version(rs.getString(1)))
        finally st.close()
    finally c.close()

  private def historyExists(c: java.sql.Connection): Boolean =
    val st = c.prepareStatement("SELECT to_regclass('flyway_schema_history') IS NOT NULL")
    try { val rs = st.executeQuery(); rs.next() && rs.getBoolean(1) }
    finally st.close()
